/// Qualified class name (`mylib.geometry.Square`) -> (module, class name).
type ClassMap = HashMap<String, (String, String)>;

/// The view classes the stubs may use, spelled `_orochi.<kind>` in hints
/// (see `IntoObject::__view_hint`). They exist only for type checkers and
/// are defined once, in the root module's stub.
const VIEW_KINDS: [&str; 3] = ["ListView", "DictView", "SetView"];

/// What every file of a module tree needs to know.
struct Tree<'a> {
    root: &'a str,
    classes: ClassMap,
    /// View kind -> its class name in the root stub.
    view_names: BTreeMap<&'static str, String>,
}

fn collect_classes(module: &Module, full: &str, out: &mut ClassMap) {
    for item in &module.items {
        match item {
            Item::Class(c) => {
                out.insert(
                    format!("{full}.{}", c.name),
                    (full.to_owned(), c.name.to_owned()),
                );
            }
            Item::Module(m) => collect_classes(m, &format!("{full}.{}", m.name), out),
            _ => {}
        }
    }
}

/// Renders the stubs of `module` and its submodules into `out`, the root
/// last: it defines the view classes that any file uses (`needed`).
fn render_tree(
    module: &Module,
    full: String,
    tree: &Tree<'_>,
    needed: &mut BTreeSet<&'static str>,
    out: &mut BTreeMap<String, String>,
) {
    for sub in module.submodules() {
        render_tree(sub, format!("{full}.{}", sub.name), tree, needed, out);
    }
    let package = module.submodules().next().is_some();
    let base = full.replace('.', "/");
    let path = if package {
        format!("{base}/__init__.pyi")
    } else {
        format!("{base}.pyi")
    };
    out.insert(path, render_module(module, &full, tree, needed));
}

/// Builtins that hints may use bare; a stub defining one of these names
/// refers to the builtin as `builtins.<name>`.
const KEYWORDS: &[&str] = &["None", "True", "False"];

/// Per-file state: imports needed by the rendered hints.
struct File<'a> {
    module: &'a str,
    tree: &'a Tree<'a>,
    /// Names defined at module level, which shadow a builtin of the same name
    /// everywhere in the file.
    defined: HashSet<&'a str>,
    /// Member names of the class being rendered (they shadow builtins and
    /// classes in the class body).
    members: HashSet<&'a str>,
    /// Names that an import or a generated private name must not take: all
    /// names defined in the file (module level and class members), the
    /// aliases and private names generated so far.
    reserved: HashSet<String>,
    /// Names bound by plain `import a.b` statements (`a`).
    import_roots: HashSet<String>,
    /// `import module` (alias `None`) or `import module as alias`.
    imports: BTreeMap<String, Option<String>>,
    /// (module, class) -> local name.
    from_imports: BTreeMap<(String, String), String>,
    /// Class of this module -> private module-level alias, for class bodies
    /// where a member shadows the class name.
    class_aliases: BTreeMap<String, String>,
    /// View kinds used in this file.
    views: BTreeSet<&'static str>,
}

impl<'a> File<'a> {
    fn new(module: &'a str, tree: &'a Tree<'a>, defined: HashSet<&'a str>) -> File<'a> {
        File {
            module,
            tree,
            defined,
            members: HashSet::new(),
            reserved: HashSet::new(),
            import_roots: HashSet::new(),
            imports: BTreeMap::new(),
            from_imports: BTreeMap::new(),
            class_aliases: BTreeMap::new(),
            views: BTreeSet::new(),
        }
    }

    /// `base`, or `base_2`, `base_3`, ... if taken; reserves the result.
    fn fresh(&mut self, base: &str) -> String {
        let mut name = base.to_owned();
        let mut n = 1;
        while self.reserved.contains(&name) || self.import_roots.contains(&name) {
            n += 1;
            name = format!("{base}_{n}");
        }
        self.reserved.insert(name.clone());
        name
    }

    /// The expression for `module` in this file, importing it.
    fn module(&mut self, module: &str) -> String {
        if let Some(alias) = self.imports.get(module) {
            return alias.clone().unwrap_or_else(|| module.to_owned());
        }
        let root = module.split('.').next().unwrap_or(module);
        let alias = if self.reserved.contains(root) {
            Some(self.fresh(&format!("_{}", module.replace('.', "_"))))
        } else {
            self.import_roots.insert(root.to_owned());
            None
        };
        self.imports.insert(module.to_owned(), alias.clone());
        alias.unwrap_or_else(|| module.to_owned())
    }

    /// A class of another module of the tree, imported with `from`.
    fn import_class(&mut self, module: &str, name: &str) -> String {
        let key = (module.to_owned(), name.to_owned());
        if let Some(local) = self.from_imports.get(&key) {
            return local.clone();
        }
        let local = if self.reserved.contains(name) || self.import_roots.contains(name) {
            self.fresh(&format!("_{}_{name}", module.replace('.', "_")))
        } else {
            self.reserved.insert(name.to_owned());
            name.to_owned()
        };
        self.from_imports.insert(key, local.clone());
        local
    }

    /// A class defined in this file: its name, or a private alias inside a
    /// class body where a member has the same name.
    fn local_class(&mut self, class: &str) -> String {
        if !self.members.contains(class) {
            return class.to_owned();
        }
        if let Some(alias) = self.class_aliases.get(class) {
            return alias.clone();
        }
        let alias = self.fresh(&format!("_{class}"));
        self.class_aliases.insert(class.to_owned(), alias.clone());
        alias
    }

    /// A (possibly dotted) name from a hint, as written in this file.
    fn name(&mut self, name: &str) -> String {
        if let Some(kind) = name.strip_prefix("_orochi.")
            && let Some(kind) = VIEW_KINDS.iter().copied().find(|k| *k == kind)
        {
            self.views.insert(kind);
            let view = self.tree.view_names[kind].clone();
            return if self.module == self.tree.root {
                self.local_class(&view)
            } else {
                self.import_class(self.tree.root, &view)
            };
        }
        if let Some((module, class)) = self.tree.classes.get(name) {
            if module == self.module {
                return self.local_class(class);
            }
            return self.import_class(module, class);
        }
        match name.rsplit_once('.') {
            Some((module, last)) => format!("{}.{last}", self.module(module)),
            None if KEYWORDS.contains(&name)
                || !(self.defined.contains(name) || self.members.contains(name)) =>
            {
                name.to_owned()
            }
            None => format!("{}.{name}", self.module("builtins")),
        }
    }

    /// Renders a hint: names imported or qualified, unions deduped. An empty
    /// hint (from a custom conversion) is `typing.Any`.
    fn hint(&mut self, hint: &str) -> String {
        if hint.trim().is_empty() {
            return self.name("typing.Any");
        }
        let mut tokens = tokenize(hint);
        for token in &mut tokens {
            if let Tok::Name(name) = &token.tok {
                token.tok = Tok::Name(self.name(name));
            }
        }
        let mut parser = Parser {
            tokens: &tokens,
            pos: 0,
        };
        match parser.union() {
            Some(node) if parser.pos == tokens.len() => render_node(&node),
            // Not a hint we understand: keep it as written.
            _ => {
                let mut out = String::new();
                for (i, token) in tokens.iter().enumerate() {
                    if token.space && i > 0 {
                        out.push(' ');
                    }
                    out.push_str(token.tok.text());
                }
                out
            }
        }
    }

    /// Fills a template: every `{hint}` is rendered with [`File::hint`].
    fn fill(&mut self, template: &str) -> String {
        let mut out = String::new();
        let mut rest = template;
        while let Some(start) = rest.find('{') {
            out.push_str(&rest[..start]);
            let end = rest[start..].find('}').expect("closed `{`") + start;
            out.push_str(&self.hint(&rest[start + 1..end]));
            rest = &rest[end + 1..];
        }
        out.push_str(rest);
        out
    }

    fn function(&mut self, f: &Function, indent: &str, kind: FnKind) -> String {
        let mut params: Vec<String> = Vec::new();
        // A parameter may be called `cls` (Rust has no `self` parameter).
        let receiver = |name: &str| {
            let mut name = name.to_owned();
            while f.params.iter().any(|p| p.name == name) {
                name.insert(0, '_');
            }
            name
        };
        match kind {
            FnKind::Method => params.push(receiver("self")),
            FnKind::New => params.push(receiver("cls")),
            FnKind::Function | FnKind::Static => {}
        }
        for p in &f.params {
            let hint = self.hint(&p.hint);
            params.push(if p.default_none {
                format!("{}: {hint} = None", p.name)
            } else {
                format!("{}: {hint}", p.name)
            });
        }
        let ret = self.hint(&f.ret);
        let mut out = String::new();
        if matches!(kind, FnKind::Static) {
            let decorator = self.name("staticmethod");
            out.push_str(&format!("{indent}@{decorator}\n"));
        }
        out.push_str(&format!(
            "{indent}def {}({}) -> {ret}:",
            f.name,
            params.join(", ")
        ));
        let body = body(f.doc, indent);
        // Pyright flags a static method whose first parameter is called
        // `self` or `cls`; that is the Python name of the Rust parameter.
        let comment = (matches!(kind, FnKind::Static)
            && f.params.first().is_some_and(|p| p.name == "self" || p.name == "cls"))
        .then_some("  # pyright: ignore[reportSelfClsParameterName]");
        match (comment, body.strip_prefix(" ...")) {
            (Some(comment), Some("")) => {
                out.push_str(" ...");
                out.push_str(comment);
            }
            (Some(comment), _) => {
                out.push_str(comment);
                out.push_str(&body);
            }
            (None, _) => out.push_str(&body),
        }
        out
    }

    fn render_class(&mut self, c: &'a Class) -> String {
        let indent = "    ";
        let mut out = format!("@{}\nclass {}:", self.name("typing.final"), c.name);
        self.members = c.members.iter().map(Member::name).collect();
        let this = self.name(&format!("{}.{}", self.module, c.name));
        let mut lines: Vec<String> = Vec::new();
        let mut members: Vec<&Member> = c.members.iter().collect();
        members.sort_by_key(|m| m.rank());
        let class_var = self.name("typing.ClassVar");
        for member in members {
            match member {
                Member::Variant(name) => {
                    let fin = self.name("typing.Final");
                    lines.push(format!("{indent}{name}: {fin}[{this}]"))
                }
                Member::Attribute(name, hint) => {
                    let hint = self.hint(hint);
                    lines.push(format!("{indent}{name}: {class_var}[{hint}]"));
                }
                Member::Init(f) => {
                    // pyo3 constructors are `__new__` (`__init__` is
                    // `object`'s), which is also what stubtest checks.
                    let new = Function {
                        name: "__new__",
                        doc: f.doc,
                        params: f
                            .params
                            .iter()
                            .map(|p| Param::new(p.name, p.hint.clone(), p.default_none))
                            .collect(),
                        ret: format!("{}.{}", self.module, c.name),
                    };
                    lines.push(self.function(&new, indent, FnKind::New));
                }
                Member::Property {
                    name,
                    doc,
                    get,
                    set,
                } => {
                    let property = self.name("property");
                    let get = self.hint(get);
                    let set = self.hint(set);
                    lines.push(format!(
                        "{indent}@{property}\n{indent}def {name}(self) -> {get}:{}",
                        body(doc, indent)
                    ));
                    lines.push(format!(
                        "{indent}@{name}.setter\n{indent}def {name}(self, value: {set}) -> None: ..."
                    ));
                }
                Member::Method(f) => lines.push(self.function(f, indent, FnKind::Method)),
                Member::Static(f) => lines.push(self.function(f, indent, FnKind::Static)),
            }
        }
        let attributes = c.members.iter().filter(|m| m.rank() == 0).count();
        // Without `new`, Python raises `TypeError`; a parameter of the
        // bottom type makes type checkers reject every call too (`NoReturn`
        // rather than `Never`, which needs Python 3.11 stubs).
        if !c.constructible && !c.members.iter().any(|m| matches!(m, Member::Init(_))) {
            let never = self.name("typing.NoReturn");
            lines.insert(
                attributes,
                format!("{indent}def __new__(cls, _not_constructible: {never}, /) -> {this}: ..."),
            );
        }
        // `__hash__` goes right after the class attributes.
        if c.unhashable {
            lines.insert(
                attributes,
                format!("{indent}__hash__: {class_var}[None]  # type: ignore[assignment]"),
            );
        }
        let doc = docstring(c.doc, indent);
        match (doc, lines.is_empty()) {
            (None, true) => out.push_str(" ..."),
            (Some(doc), true) => out.push_str(&format!("\n{indent}{doc}")),
            (Some(doc), false) => out.push_str(&format!("\n{indent}{doc}\n\n{}", lines.join("\n"))),
            (None, false) => out.push_str(&format!("\n{}", lines.join("\n"))),
        }
        self.members.clear();
        out
    }

    /// The `TypeVar`s and `@typing.type_check_only` classes of the views in
    /// `kinds` (root module only).
    fn view_classes(&mut self, kinds: &BTreeSet<&'static str>) -> (Vec<String>, Vec<String>) {
        if kinds.is_empty() {
            return (Vec::new(), Vec::new());
        }
        let templates: Vec<String> = VIEW_KINDS
            .iter()
            .filter(|kind| kinds.contains(*kind))
            .map(|kind| {
                let mut template = match *kind {
                    "ListView" => LIST_VIEW,
                    "DictView" => DICT_VIEW,
                    _ => SET_VIEW,
                }
                .to_owned();
                for kind in VIEW_KINDS {
                    template = template.replace(&format!("${kind}"), &self.tree.view_names[kind]);
                }
                template
            })
            .collect();
        // Type variables, declared if used: `$X` not followed by more of a name.
        let used = |key: &str| {
            let pattern = format!("${key}");
            templates.iter().any(|t| {
                t.match_indices(&pattern).any(|(i, _)| {
                    !t[i + pattern.len()..].starts_with(|c: char| c.is_ascii_alphanumeric())
                })
            })
        };
        let type_var = self.name("typing.TypeVar");
        let any = self.name("typing.Any");
        let mut declarations = Vec::new();
        let mut names: Vec<(String, String)> = Vec::new();
        for (key, bound) in [
            ("T", None),
            ("I", None),
            ("P", None),
            ("K", None),
            ("V", None),
            ("S", None),
            ("LV", Some(("ListView", 3))),
            ("DV", Some(("DictView", 4))),
        ] {
            if !used(key) {
                continue;
            }
            let name = self.fresh(&format!("_{key}"));
            let bound = match bound {
                Some((kind, args)) => {
                    let view = self.local_class(&self.tree.view_names[kind].clone());
                    format!(", bound={view}[{}]", vec![any.as_str(); args].join(", "))
                }
                None => String::new(),
            };
            declarations.push(format!("{name} = {type_var}(\"{name}\"{bound})"));
            names.push((format!("${key}"), name));
        }
        // No key is a prefix of another, so the order does not matter.
        let classes = templates
            .into_iter()
            .map(|mut template| {
                for (key, name) in &names {
                    template = template.replace(key, name);
                }
                self.fill(&template)
            })
            .collect();
        (declarations, classes)
    }
}

