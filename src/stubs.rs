/// A module: built by the generated `__orochi_stub_module()` functions.
#[doc(hidden)]
pub struct Module {
    name: &'static str,
    doc: &'static str,
    items: Vec<Item>,
}

enum Item {
    Function(Function),
    Class(Class),
    Constant(&'static str, String),
    Module(Module),
}

#[doc(hidden)]
impl Module {
    pub fn new(name: &'static str, doc: &'static str) -> Module {
        Module {
            name,
            doc,
            items: Vec::new(),
        }
    }
    pub fn function(&mut self, function: Function) {
        self.items.push(Item::Function(function));
    }
    pub fn class(&mut self, class: Class) {
        self.items.push(Item::Class(class));
    }
    pub fn constant(&mut self, name: &'static str, hint: String) {
        self.items.push(Item::Constant(name, hint));
    }
    pub fn module(&mut self, module: Module) {
        self.items.push(Item::Module(module));
    }

    fn submodules(&self) -> impl Iterator<Item = &Module> {
        self.items.iter().filter_map(|item| match item {
            Item::Module(m) => Some(m),
            _ => None,
        })
    }
}

/// A function, method, static method or constructor.
#[doc(hidden)]
pub struct Function {
    name: &'static str,
    doc: &'static str,
    params: Vec<Param>,
    ret: String,
}

#[doc(hidden)]
impl Function {
    pub fn new(name: &'static str, doc: &'static str, params: Vec<Param>, ret: String) -> Function {
        Function {
            name,
            doc,
            params,
            ret,
        }
    }
}

#[doc(hidden)]
pub struct Param {
    name: &'static str,
    hint: String,
    default_none: bool,
}

#[doc(hidden)]
impl Param {
    pub fn new(name: &'static str, hint: String, default_none: bool) -> Param {
        Param {
            name,
            hint,
            default_none,
        }
    }
}

/// A class (struct or enum).
#[doc(hidden)]
pub struct Class {
    name: &'static str,
    doc: &'static str,
    unhashable: bool,
    /// Has a constructor (`pub fn new`).
    constructible: bool,
    members: Vec<Member>,
}

enum Member {
    Variant(&'static str),
    Attribute(&'static str, String),
    Init(Function),
    Property {
        name: &'static str,
        doc: &'static str,
        get: String,
        set: String,
    },
    Method(Function),
    Static(Function),
}

impl Member {
    fn name(&self) -> &'static str {
        match self {
            Member::Variant(name) | Member::Attribute(name, _) => name,
            Member::Property { name, .. } => name,
            Member::Init(f) | Member::Method(f) | Member::Static(f) => f.name,
        }
    }

    /// Render order: class attributes, constructor, properties, methods.
    fn rank(&self) -> u8 {
        match self {
            Member::Variant(_) | Member::Attribute(..) => 0,
            Member::Init(_) => 1,
            Member::Property { .. } => 2,
            Member::Method(_) | Member::Static(_) => 3,
        }
    }
}

#[doc(hidden)]
impl Class {
    pub fn new(
        name: &'static str,
        doc: &'static str,
        unhashable: bool,
        constructible: bool,
    ) -> Class {
        Class {
            name,
            doc,
            unhashable,
            constructible,
            members: Vec::new(),
        }
    }
    pub fn variant(&mut self, name: &'static str) {
        self.members.push(Member::Variant(name));
    }
    pub fn attribute(&mut self, name: &'static str, hint: String) {
        self.members.push(Member::Attribute(name, hint));
    }
    pub fn init(&mut self, function: Function) {
        self.members.push(Member::Init(function));
    }
    pub fn property(&mut self, name: &'static str, doc: &'static str, get: String, set: String) {
        self.members.push(Member::Property {
            name,
            doc,
            get,
            set,
        });
    }
    pub fn method(&mut self, function: Function) {
        self.members.push(Member::Method(function));
    }
    pub fn static_method(&mut self, function: Function) {
        self.members.push(Member::Static(function));
    }
}


