/// The body of a `def`: ` ...` or an indented docstring.
fn body(doc: &str, indent: &str) -> String {
    let inner = format!("{indent}    ");
    match docstring(doc, &inner) {
        Some(doc) => format!("\n{inner}{doc}"),
        None => " ...".to_owned(),
    }
}

/// `doc` as a triple-quoted string literal whose continuation lines are
/// indented by `indent`; `None` for an empty doc.
fn docstring(doc: &str, indent: &str) -> Option<String> {
    let doc = doc.replace("\r\n", "\n");
    let doc = doc.trim();
    if doc.is_empty() {
        return None;
    }
    let chars: Vec<char> = doc.chars().collect();
    let mut text = String::new();
    // Unescaped `"` just written: a third one would close the literal.
    let mut quotes = 0;
    for (i, &c) in chars.iter().enumerate() {
        match c {
            // Escaped when it would make `"""`, and at the very end (where it
            // would merge with the closing quotes).
            '"' if quotes == 2 || i + 1 == chars.len() => {
                text.push_str("\\\"");
                quotes = 0;
            }
            '"' => {
                text.push('"');
                quotes += 1;
            }
            '\\' => text.push_str("\\\\"),
            '\n' | '\t' => text.push(c),
            c if (c as u32) < 0x20 || c == '\x7f' => text.push_str(&format!("\\x{:02x}", c as u32)),
            c => text.push(c),
        }
        if c != '"' {
            quotes = 0;
        }
    }
    let lines: Vec<&str> = text.split('\n').collect();
    if lines.len() == 1 {
        return Some(format!("\"\"\"{text}\"\"\""));
    }
    let mut out = format!("\"\"\"{}", lines[0]);
    for line in &lines[1..] {
        out.push('\n');
        if !line.trim().is_empty() {
            out.push_str(indent);
            out.push_str(line);
        }
    }
    out.push('\n');
    out.push_str(indent);
    out.push_str("\"\"\"");
    Some(out)
}

/// Every Python name a module's stub defines: its items and their members.
fn defined_names(module: &Module) -> (HashSet<&str>, HashSet<&str>) {
    let mut defined: HashSet<&str> = HashSet::new();
    let mut all: HashSet<&str> = HashSet::new();
    for item in &module.items {
        defined.insert(match item {
            Item::Function(f) => f.name,
            Item::Class(c) => {
                all.extend(c.members.iter().map(Member::name));
                c.name
            }
            Item::Constant(name, _) => name,
            Item::Module(m) => m.name,
        });
    }
    all.extend(&defined);
    (defined, all)
}

fn render_module(
    module: &Module,
    full: &str,
    tree: &Tree<'_>,
    needed: &mut BTreeSet<&'static str>,
) -> String {
    let is_root = full == tree.root;
    let (defined, all_defined) = defined_names(module);
    let mut file = File::new(full, tree, defined);
    file.reserved = all_defined.iter().map(|n| (*n).to_owned()).collect();
    if is_root {
        file.reserved.extend(tree.view_names.values().cloned());
    }

    let mut blocks: Vec<String> = Vec::new();
    let mut submodules: Vec<&str> = Vec::new();
    // pyo3 lists every name added to a module in its `__all__`.
    let mut all: Vec<&str> = Vec::new();
    for item in &module.items {
        all.push(match item {
            Item::Function(f) => f.name,
            Item::Class(c) => c.name,
            Item::Constant(name, _) => name,
            Item::Module(m) => m.name,
        });
        match item {
            Item::Function(f) => blocks.push(file.function(f, "", FnKind::Function)),
            Item::Class(c) => blocks.push(file.render_class(c)),
            Item::Constant(name, hint) => {
                let fin = file.name("typing.Final");
                let hint = file.hint(hint);
                blocks.push(format!("{name}: {fin}[{hint}]"));
            }
            Item::Module(m) => submodules.push(m.name),
        }
    }
    needed.extend(file.views.iter().copied());
    let (type_vars, view_classes) = if is_root {
        let kinds = needed.clone();
        file.view_classes(&kinds)
    } else {
        (Vec::new(), Vec::new())
    };

    let mut intro = String::from(HEADER);
    if let Some(doc) = docstring(module.doc, "") {
        intro.push('\n');
        intro.push_str(&doc);
    }
    let mut header: Vec<String> = Vec::new();
    for (module, alias) in &file.imports {
        header.push(match alias {
            Some(alias) => format!("import {module} as {alias}"),
            None => format!("import {module}"),
        });
    }
    for name in &submodules {
        // `as` marks an explicit re-export: `mylib.geometry` is an attribute.
        header.push(format!("from . import {name} as {name}"));
    }
    let mut by_module: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    for ((module, name), local) in &file.from_imports {
        by_module.entry(module).or_default().push(if local == name {
            name.clone()
        } else {
            format!("{name} as {local}")
        });
    }
    for (module, names) in by_module {
        header.push(format!("from {module} import {}", names.join(", ")));
    }
    // Private names: class aliases (see `File::local_class`), type variables.
    let mut private: Vec<String> = file
        .class_aliases
        .iter()
        .map(|(class, alias)| format!("{alias} = {class}"))
        .collect();
    private.extend(type_vars);
    blocks.extend(view_classes);
    // Single-line items stay together; multi-line ones get blank lines.
    let mut items = String::new();
    let mut previous_multiline = false;
    for (i, block) in blocks.iter().enumerate() {
        let multiline = block.contains('\n');
        if i > 0 {
            items.push_str(if multiline || previous_multiline {
                "\n\n"
            } else {
                "\n"
            });
        }
        items.push_str(block);
        previous_multiline = multiline;
    }
    let mut sections = vec![intro];
    if !header.is_empty() {
        sections.push(header.join("\n"));
    }
    if !all.is_empty() {
        let names: Vec<String> = all
            .iter()
            .map(|name| format!("    \"{name}\",\n"))
            .collect();
        sections.push(format!("__all__ = [\n{}]", names.concat()));
    }
    if !private.is_empty() {
        sections.push(private.join("\n"));
    }
    if !items.is_empty() {
        sections.push(items);
    }
    sections.join("\n\n") + "\n"
}

/// The first line of every generated stub file (also how `write_stubs`
/// recognizes the files it may replace).
const HEADER: &str = "# Type stubs generated by orochi from the Rust sources.";

// ---------------------------------------------------------------- hint parsing

enum Tok {
    /// A (dotted) name.
    Name(String),
    /// A string or number literal, or `...`.
    Literal(String),
    /// One of `[](),|`.
    Punct(char),
    /// Anything else (the hint is then kept as written).
    Other(String),
}

impl Tok {
    fn text(&self) -> &str {
        match self {
            Tok::Name(s) | Tok::Literal(s) | Tok::Other(s) => s,
            Tok::Punct(c) => match c {
                '[' => "[",
                ']' => "]",
                '(' => "(",
                ')' => ")",
                ',' => ",",
                _ => "|",
            },
        }
    }
}

struct Token {
    tok: Tok,
    /// Whitespace before the token in the original hint.
    space: bool,
}

fn is_ident_start(c: char) -> bool {
    c == '_' || c.is_alphabetic()
}

fn is_ident_continue(c: char) -> bool {
    c == '_' || c.is_alphanumeric()
}

fn tokenize(hint: &str) -> Vec<Token> {
    let chars: Vec<char> = hint.chars().collect();
    let mut tokens = Vec::new();
    let mut i = 0;
    let mut space = false;
    while i < chars.len() {
        let c = chars[i];
        if c.is_whitespace() {
            space = true;
            i += 1;
            continue;
        }
        let start = i;
        let tok = if is_ident_start(c) {
            i += 1;
            loop {
                while i < chars.len() && is_ident_continue(chars[i]) {
                    i += 1;
                }
                if i + 1 < chars.len() && chars[i] == '.' && is_ident_start(chars[i + 1]) {
                    i += 1;
                } else {
                    break;
                }
            }
            Tok::Name(chars[start..i].iter().collect())
        } else if c == '"' || c == '\'' {
            i += 1;
            while i < chars.len() && chars[i] != c {
                if chars[i] == '\\' {
                    i += 1;
                }
                i += 1;
            }
            i = (i + 1).min(chars.len());
            Tok::Literal(chars[start..i].iter().collect())
        } else if c.is_ascii_digit()
            || (c == '-' && chars.get(i + 1).is_some_and(|d| d.is_ascii_digit()))
        {
            i += 1;
            while i < chars.len() && (is_ident_continue(chars[i]) || chars[i] == '.') {
                i += 1;
            }
            Tok::Literal(chars[start..i].iter().collect())
        } else if chars[i..].starts_with(&['.', '.', '.']) {
            i += 3;
            Tok::Literal("...".to_owned())
        } else if "[](),|".contains(c) {
            i += 1;
            Tok::Punct(c)
        } else {
            i += 1;
            Tok::Other(c.to_string())
        };
        tokens.push(Token { tok, space });
        space = false;
    }
    tokens
}

enum Node {
    Union(Vec<Node>),
    /// `name` or `name[args]` (also literals).
    Atom(String, Option<Vec<Node>>),
    /// `[a, b]` (e.g. `Callable` parameters).
    List(Vec<Node>),
    /// `(a, b)`; the flag is a trailing comma.
    Tuple(Vec<Node>, bool),
}

struct Parser<'a> {
    tokens: &'a [Token],
    pos: usize,
}

impl Parser<'_> {
    fn eat(&mut self, punct: char) -> bool {
        if matches!(self.tokens.get(self.pos), Some(Token { tok: Tok::Punct(c), .. }) if *c == punct)
        {
            self.pos += 1;
            true
        } else {
            false
        }
    }

    fn union(&mut self) -> Option<Node> {
        let mut parts = vec![self.atom()?];
        while self.eat('|') {
            parts.push(self.atom()?);
        }
        Some(if parts.len() == 1 {
            parts.pop().expect("one part")
        } else {
            Node::Union(parts)
        })
    }

    fn atom(&mut self) -> Option<Node> {
        let token = self.tokens.get(self.pos)?;
        self.pos += 1;
        match &token.tok {
            Tok::Name(name) => {
                let args = if self.eat('[') {
                    Some(self.list(']')?.0)
                } else {
                    None
                };
                Some(Node::Atom(name.clone(), args))
            }
            Tok::Literal(text) => Some(Node::Atom(text.clone(), None)),
            Tok::Punct('[') => Some(Node::List(self.list(']')?.0)),
            Tok::Punct('(') => {
                let (items, trailing) = self.list(')')?;
                Some(Node::Tuple(items, trailing))
            }
            _ => None,
        }
    }

    /// Comma-separated items up to `close`; also says whether there was a
    /// trailing comma.
    fn list(&mut self, close: char) -> Option<(Vec<Node>, bool)> {
        let mut items = Vec::new();
        if self.eat(close) {
            return Some((items, false));
        }
        loop {
            items.push(self.union()?);
            if self.eat(',') {
                if self.eat(close) {
                    return Some((items, true));
                }
            } else if self.eat(close) {
                return Some((items, false));
            } else {
                return None;
            }
        }
    }
}

fn render_node(node: &Node) -> String {
    fn join(items: &[Node]) -> String {
        items.iter().map(render_node).collect::<Vec<_>>().join(", ")
    }
    fn flatten<'a>(node: &'a Node, out: &mut Vec<&'a Node>) {
        match node {
            Node::Union(parts) => parts.iter().for_each(|p| flatten(p, out)),
            other => out.push(other),
        }
    }
    match node {
        Node::Union(_) => {
            let mut parts = Vec::new();
            flatten(node, &mut parts);
            let mut seen = BTreeSet::new();
            let mut out: Vec<String> = Vec::new();
            for part in parts {
                let text = render_node(part);
                if seen.insert(text.clone()) {
                    out.push(text);
                }
            }
            out.join(" | ")
        }
        Node::Atom(name, None) => name.clone(),
        Node::Atom(name, Some(args)) => format!("{name}[{}]", join(args)),
        Node::List(items) => format!("[{}]", join(items)),
        Node::Tuple(items, trailing) => {
            if *trailing && items.len() == 1 {
                format!("({},)", join(items))
            } else {
                format!("({})", join(items))
            }
        }
    }
}

