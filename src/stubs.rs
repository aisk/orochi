//! `.pyi` type stubs for modules defined with `#[orochi::module]`.
//!
//! The macro describes every exported item (names, parameters, defaults,
//! docstrings, and type hints from [`FromObject::input_hint`] /
//! [`IntoObject::output_hint`]); [`Stubs`] renders that description as stub
//! files. Rendering is plain Rust: no Python interpreter is needed.
//!
//! Hints are fully qualified strings (`collections.abc.Sequence[int]`,
//! `mylib.geometry.Square`). The renderer parses them, imports what they
//! use (`import collections.abc`; classes of the module tree with
//! `from mylib.geometry import Square`, or as a bare name within their own
//! module), dedupes unions and avoids names that a stub's own definitions
//! would shadow (`builtins.str` in a class with a `str` attribute). Hints it
//! cannot parse are kept as they are, with their dotted names still imported.
//!
//! [`FromObject::input_hint`]: crate::FromObject::input_hint
//! [`IntoObject::output_hint`]: crate::IntoObject::output_hint

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::path::{Path, PathBuf};

/// The `.pyi` type stubs of an `#[orochi::module]` and its submodules.
///
/// Get them from the generated accessor `<module>::__orochi_stubs()`, e.g. in
/// a test of the extension crate, and write them with [`write_stubs`]:
///
/// ```
/// #[orochi::module]
/// mod mylib {
///     /// Add two integers.
///     pub fn add(a: i64, b: Option<i64>) -> i64 {
///         a + b.unwrap_or(1)
///     }
/// }
///
/// let files = mylib::__orochi_stubs().files();
/// assert!(files["mylib.pyi"].contains("def add(a: int, b: int | None = None) -> int:"));
/// // orochi::write_stubs(&mylib::__orochi_stubs(), "typings")?;
/// ```
///
/// From Python, the built module offers the same through a hidden function:
/// `python -c "import mylib; mylib._orochi_stubs('typings')"`.
pub struct Stubs {
    root: Module,
}

impl Stubs {
    pub(crate) fn new(root: Module) -> Stubs {
        Stubs { root }
    }

    /// The stub files, by path relative to the output directory (with `/`
    /// separators): `mylib.pyi` for a module without submodules, otherwise a
    /// stub package `mylib/__init__.pyi`, `mylib/geometry.pyi`, ...
    pub fn files(&self) -> BTreeMap<String, String> {
        let mut classes = HashMap::new();
        collect_classes(&self.root, self.root.name, &mut classes);
        // The view classes are defined in the root stub, under names that
        // its own items do not use.
        let (_, root_names) = defined_names(&self.root);
        let view_names = VIEW_KINDS
            .iter()
            .map(|kind| {
                let mut name = (*kind).to_owned();
                let mut n = 1;
                while root_names.contains(name.as_str()) {
                    n += 1;
                    name = format!("{kind}_{n}");
                }
                (*kind, name)
            })
            .collect();
        let tree = Tree {
            root: self.root.name,
            classes,
            view_names,
        };
        let mut out = BTreeMap::new();
        let mut needed = BTreeSet::new();
        render_tree(
            &self.root,
            self.root.name.to_owned(),
            &tree,
            &mut needed,
            &mut out,
        );
        out
    }
}

/// Writes the stub files of `stubs` into `dir` (created if needed) and
/// returns their paths. See [`Stubs::files`] for the layout.
///
/// Stubs written earlier in the other layout are removed first, so that
/// `mylib.pyi` and a `mylib/` stub package never shadow each other after
/// submodules were added or removed: `dir/mylib.pyi` when writing a package,
/// the `.pyi` files under `dir/mylib/` when writing `mylib.pyi`. Only files
/// that start with the comment orochi writes are removed (then directories
/// left empty); nothing else is touched.
pub fn write_stubs(stubs: &Stubs, dir: impl AsRef<Path>) -> std::io::Result<Vec<PathBuf>> {
    let dir = dir.as_ref();
    let files = stubs.files();
    let name = stubs.root.name;
    if files.contains_key(&format!("{name}.pyi")) {
        remove_generated_tree(&dir.join(name))?;
    } else {
        remove_generated(&dir.join(format!("{name}.pyi")))?;
    }
    let mut written = Vec::new();
    for (relative, text) in files {
        let mut path = dir.to_path_buf();
        path.extend(relative.split('/'));
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, text)?;
        written.push(path);
    }
    Ok(written)
}

/// Removes `path` if it is a stub file generated by orochi.
fn remove_generated(path: &Path) -> std::io::Result<()> {
    if path.extension().is_some_and(|e| e == "pyi")
        && path.is_file()
        && std::fs::read_to_string(path).is_ok_and(|text| text.starts_with(HEADER))
    {
        std::fs::remove_file(path)?;
    }
    Ok(())
}

/// Removes the generated stub files under `dir`, then the directories that
/// this left empty.
fn remove_generated_tree(dir: &Path) -> std::io::Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            remove_generated_tree(&path)?;
        } else {
            remove_generated(&path)?;
        }
    }
    if std::fs::read_dir(dir)?.next().is_none() {
        std::fs::remove_dir(dir)?;
    }
    Ok(())
}

