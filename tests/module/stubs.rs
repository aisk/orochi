#[test]
fn receiver_names_do_not_clash_with_parameters() {
    #[orochi::module]
    mod clash {
        pub struct Kind {
            pub cls: String,
        }

        impl Kind {
            pub fn new(cls: String) -> Self {
                Kind { cls }
            }

            /// A static method whose first parameter is called `cls`.
            pub fn of(cls: String) -> Kind {
                Kind { cls }
            }

            pub fn plain(cls: i64) -> i64 {
                cls
            }

            pub fn named(&self, cls: &str) -> bool {
                self.cls == cls
            }
        }
    }
    let text = &clash::__orochi_stubs().files()["clash.pyi"];
    has_lines(
        text,
        &[
            "    def __new__(_cls, cls: str) -> Kind: ...",
            // That is the Python name of the parameter, which pyright would
            // flag in a static method.
            "    def of(cls: str) -> Kind:  # pyright: ignore[reportSelfClsParameterName]",
            "    def plain(cls: int) -> int: ...  # pyright: ignore[reportSelfClsParameterName]",
            "    def named(self, cls: str) -> bool: ...",
        ],
    );
    let s = scope();
    s.set("text", text.as_str()).unwrap();
    s.exec("compile(text, 'clash.pyi', 'exec')").unwrap();
}

