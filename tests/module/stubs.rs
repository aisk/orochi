#[test]
fn view_classes_are_defined_once_where_needed() {
    let root = root();
    for class in ["ListView", "DictView", "SetView"] {
        let header = format!("@_typing.type_check_only\nclass {class}(");
        assert_eq!(root.matches(&header).count(), 1, "{class}");
    }
    has_lines(
        &root,
        &[
            "_T = _typing.TypeVar(\"_T\")",
            "_LV = _typing.TypeVar(\"_LV\", bound=ListView[_typing.Any, _typing.Any, _typing.Any])",
        ],
    );
    for (path, text) in files() {
        if path != "mylib/__init__.pyi" {
            assert!(!text.contains("View") && !text.contains("TypeVar"), "{path}");
        }
    }

    // None without container fields or `&mut` containers.
    #[orochi::module]
    mod plain {
        pub fn f(xs: Vec<i64>) -> Vec<i64> {
            xs
        }
    }
    let text = &plain::__orochi_stubs().files()["plain.pyi"];
    assert!(!text.contains("View") && !text.contains("TypeVar"), "{text}");

    // Used only in a submodule: defined in the root, imported there.
    #[orochi::module]
    mod tree {
        pub mod sub {
            pub struct Holder {
                pub tags: std::collections::BTreeSet<String>,
            }
        }
    }
    let files = tree::__orochi_stubs().files();
    let root = &files["tree/__init__.pyi"];
    has_lines(root, &["class SetView(collections.abc.MutableSet[_T]):"]);
    assert!(!root.contains("ListView") && !root.contains("_K"), "{root}");
    has_lines(
        &files["tree/sub.pyi"],
        &[
            "from tree import SetView",
            "    def tags(self) -> SetView[str]: ...",
        ],
    );
}

#[test]
fn members_named_like_classes_use_an_alias() {
    #[orochi::module]
    mod shapes {
        pub struct Circle {
            pub r: f64,
        }

        pub enum Shape {
            Circle,
            Square,
        }

        impl Shape {
            pub fn as_circle(&self) -> Option<Circle> {
                matches!(self, Shape::Circle).then_some(Circle { r: 1.0 })
            }
        }

        /// A member named like its own enum.
        pub enum Kind {
            Kind,
            Other,
        }

        pub struct Square;

        impl Square {
            /// A class constant named like a class.
            #[allow(non_upper_case_globals)]
            pub const Circle: f64 = 1.0;

            pub fn new() -> Self {
                Square
            }

            pub fn circle(&self) -> Circle {
                Circle { r: 0.5 }
            }

            pub fn shape(&self) -> Shape {
                Shape::Square
            }
        }
    }
    let text = &shapes::__orochi_stubs().files()["shapes.pyi"];
    has_lines(
        text,
        &[
            "_Circle = Circle",
            "_Kind = Kind",
            "    Circle: typing.Final[Shape]",
            "    def as_circle(self) -> _Circle | None: ...",
            "    Kind: typing.Final[_Kind]",
            "    Other: typing.Final[_Kind]",
            "    def __new__(cls, _not_constructible: typing.NoReturn, /) -> _Kind: ...",
            "    Circle: typing.ClassVar[float]",
            "    def circle(self) -> _Circle: ...",
            // Not shadowed in that class.
            "    def shape(self) -> Shape: ...",
        ],
    );
    let s = scope();
    s.set("text", text.as_str()).unwrap();
    s.exec("compile(text, 'shapes.pyi', 'exec')").unwrap();
}

