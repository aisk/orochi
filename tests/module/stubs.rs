const HEADER: &str = "# Type stubs generated by orochi from the Rust sources.\n";

#[test]
fn write_stubs_replaces_the_other_layout() {
    #[orochi::module]
    mod lone {
        pub fn f() {}
    }
    let dir = TempDir::new("stubs-layout");
    let path = |p: &str| dir.0.join(p);
    let write = |p: &str, text: &str| {
        std::fs::create_dir_all(path(p).parent().unwrap()).unwrap();
        std::fs::write(path(p), text).unwrap();
    };

    // A package's stubs replace a generated `mylib.pyi`...
    write("mylib.pyi", HEADER);
    orochi::write_stubs(&mylib::__orochi_stubs(), &dir.0).unwrap();
    assert!(!path("mylib.pyi").exists() && path("mylib/__init__.pyi").is_file());
    // ... but not a hand-written one.
    write("mylib.pyi", "x: int\n");
    orochi::write_stubs(&mylib::__orochi_stubs(), &dir.0).unwrap();
    assert_eq!(std::fs::read_to_string(path("mylib.pyi")).unwrap(), "x: int\n");

    // A single file replaces the generated files of a package, and the
    // directories left empty; other files stay.
    write("lone/__init__.pyi", HEADER);
    write("lone/sub/__init__.pyi", HEADER);
    write("lone/sub/deep.pyi", HEADER);
    orochi::write_stubs(&lone::__orochi_stubs(), &dir.0).unwrap();
    assert!(path("lone.pyi").is_file() && !path("lone").exists());
    write("lone/__init__.pyi", HEADER);
    write("lone/py.typed", "");
    write("lone/extra.pyi", "def g() -> None: ...\n");
    orochi::write_stubs(&lone::__orochi_stubs(), &dir.0).unwrap();
    assert!(!path("lone/__init__.pyi").exists());
    assert!(path("lone/py.typed").is_file() && path("lone/extra.pyi").is_file());
}
