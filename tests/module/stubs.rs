/// The stubs against the runtime module: `__all__`, that every class,
/// function, method and attribute exists with the same kind, and that
/// parameter names, order and defaults match `inspect.signature`.
#[test]
fn stubs_agree_with_the_runtime_module() {
    run(r#"
        import ast, importlib, inspect, types

        def stub_params(node, receiver):
            args = node.args
            assert not args.kwonlyargs and not args.vararg and not args.kwarg, node.name
            positional = args.posonlyargs + args.args
            defaults = [None] * (len(positional) - len(args.defaults)) + args.defaults
            params = []
            for arg, default in zip(positional, defaults):
                if default is not None:
                    assert isinstance(default, ast.Constant) and default.value is None, node.name
                params.append((arg.arg, default is not None))
            return params[1:] if receiver else params

        def runtime_params(obj, receiver):
            params = list(inspect.signature(obj).parameters.values())
            for p in params:
                assert p.default is p.empty or p.default is None, (obj, p)
            out = [(p.name, p.default is not p.empty) for p in params]
            return out[1:] if receiver else out

        def decorators(node):
            return [ast.unparse(d) for d in node.decorator_list]

        checked = 0
        for path, text in mylib._orochi_stubs().items():
            name = path.removesuffix(".pyi").removesuffix("/__init__").replace("/", ".")
            module = importlib.import_module(name)
            for node in ast.parse(text).body:
                if isinstance(node, ast.Assign) and node.targets[0].id == "__all__":
                    # Same names; the runtime adds classes after functions.
                    stub_all = ast.literal_eval(node.value)
                    assert len(stub_all) == len(module.__all__), name
                    assert set(stub_all) == set(module.__all__), (name, set(stub_all) ^ set(module.__all__))
                elif isinstance(node, ast.Assign):
                    # Private aliases and type variables for type checkers.
                    assert node.targets[0].id.startswith("_"), ast.unparse(node)
                elif isinstance(node, ast.AnnAssign):
                    assert hasattr(module, node.target.id), (name, node.target.id)
                elif isinstance(node, ast.FunctionDef):
                    what = f"{name}.{node.name}"
                    assert stub_params(node, False) == runtime_params(getattr(module, node.name), False), what
                    checked += 1
                elif isinstance(node, ast.ClassDef):
                    if any(d.endswith("type_check_only") for d in decorators(node)):
                        assert not hasattr(module, node.name), node.name
                        continue
                    cls = getattr(module, node.name)
                    assert isinstance(cls, type), node.name
                    for member in node.body:
                        if isinstance(member, ast.AnnAssign):
                            attr = member.target.id
                            assert attr in cls.__dict__, (cls, attr)
                            if attr == "__hash__":
                                assert cls.__hash__ is None, cls
                            continue
                        if not isinstance(member, ast.FunctionDef):
                            continue
                        what = f"{name}.{node.name}.{member.name}"
                        raw = inspect.getattr_static(cls, member.name)
                        kinds = decorators(member)
                        if member.name == "__new__" and member.args.posonlyargs:
                            # Not constructible.
                            try:
                                cls()
                            except TypeError:
                                pass
                            else:
                                raise AssertionError(what)
                        elif member.name == "__new__":
                            assert stub_params(member, True) == runtime_params(cls, False), what
                        elif "property" in kinds or any(k.endswith(".setter") for k in kinds):
                            assert isinstance(raw, types.GetSetDescriptorType), what
                        elif "staticmethod" in kinds:
                            assert isinstance(raw, staticmethod), what
                            assert stub_params(member, False) == runtime_params(raw.__func__, False), what
                        else:
                            assert not isinstance(raw, (staticmethod, classmethod)), what
                            assert stub_params(member, True) == runtime_params(raw, True), what
                        checked += 1
        assert checked > 100, checked
    "#);
}

/// A fresh directory under the system temp dir, removed on drop.
struct TempDir(std::path::PathBuf);

impl TempDir {
    fn new(name: &str) -> TempDir {
        let dir = std::env::temp_dir().join(format!("orochi-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        TempDir(dir)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

#[test]
