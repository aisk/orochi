//! `.pyi` type stubs generated for `mylib`.

use std::collections::BTreeMap;

use crate::{mylib, run, scope};

fn files() -> BTreeMap<String, String> {
    mylib::__orochi_stubs().files()
}

fn root() -> String {
    files()["mylib/__init__.pyi"].clone()
}

/// Asserts that `text` has each of `lines` as a whole line.
#[track_caller]
fn has_lines(text: &str, lines: &[&str]) {
    for line in lines {
        assert!(
            text.lines().any(|l| l == *line),
            "missing line {line:?} in:\n{text}"
        );
    }
}

/// The lines of class `name`'s block.
fn class_block(text: &str, name: &str) -> String {
    let start = text
        .find(&format!("\nclass {name}:"))
        .unwrap_or_else(|| panic!("no class {name} in:\n{text}"));
    let rest = &text[start + 1..];
    // Up to the next top-level item.
    let end = rest
        .match_indices("\n\n")
        .map(|(i, _)| i)
        .find(|&i| !rest[i + 2..].starts_with(' '))
        .unwrap_or(rest.len());
    rest[..end].to_owned()
}

